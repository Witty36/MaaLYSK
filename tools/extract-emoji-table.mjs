import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const mdPath = process.argv[2] || path.resolve(rootDir, 'docs', 'zh_cn', 'develop', '2.2-Emoji对照表.md');

const lines = fs.readFileSync(mdPath, 'utf-8').split('\n');

let currentSection = null;   // H2: { id, title, categories: [] }
const sections = [];         // array of sections

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];

  // Skip the H1 title line and non-content
  if (line.startsWith('# ')) continue;

  // H2: new section
  const h2Match = line.match(/^## (.+)/);
  if (h2Match) {
    if (currentSection) sections.push(currentSection);
    currentSection = {
      id: slugify(h2Match[1]),
      title: h2Match[1].trim(),
      categories: [],
    };
    continue;
  }

  // H3: new category within current section
  const h3Match = line.match(/^### (.+)/);
  if (h3Match && currentSection) {
    currentSection.currentCategory = {
      id: slugify(h3Match[1]),
      title: h3Match[1].trim(),
      items: [],
    };
    currentSection.categories.push(currentSection.currentCategory);
    continue;
  }

  // Table header row: skip it
  if (line.includes('| Emoji ') || line.includes('| :-----:') || line.includes('|:-----:')) {
    // If we see a table header and no category is set, create a default one for this section
    if (currentSection && !currentSection.currentCategory) {
      currentSection.currentCategory = {
        id: slugify(currentSection.title),
        title: currentSection.title,
        items: [],
      };
      currentSection.categories.push(currentSection.currentCategory);
    }
    continue;
  }

  // Table data row: | emoji | name | emoji | name |
  if (line.startsWith('|') && currentSection?.currentCategory) {
    const cols = line.split('|').map(c => c.trim()).filter(c => c !== '');
    // cols should be 2 or 4 (emoji, name, emoji, name)
    if (cols.length >= 2) {
      currentSection.currentCategory.items.push({ e: cols[0], n: cols[1] });
    }
    if (cols.length >= 4 && cols[2] && cols[3]) {
      currentSection.currentCategory.items.push({ e: cols[2], n: cols[3] });
    }
    continue;
  }

  // Horizontal rules, blank lines: skip
  if (line.startsWith('---') || line.trim() === '' || line.startsWith('>')) {
    continue;
  }
}

// Don't forget the last section
if (currentSection) sections.push(currentSection);

// Clean up internal properties
for (const sec of sections) {
  delete sec.currentCategory;
  for (const cat of sec.categories) {
    delete cat.currentCategory;
  }
}

// Count total
let total = 0;
for (const sec of sections) {
  for (const cat of sec.categories) {
    total += cat.items.length;
  }
}

console.log(`Extracted: ${sections.length} sections, ${sections.reduce((s, sec) => s + sec.categories.length, 0)} categories, ${total} emojis`);

// Generate TypeScript output
const outPath = path.resolve(rootDir, 'docs', '.vitepress', 'theme', 'components', 'emojiData.ts');

let output = `// Auto-generated by tools/extract-emoji-table.mjs
// DO NOT EDIT MANUALLY — regenerate when emoji table changes

export interface EmojiEntry {
  e: string;   // emoji character
  n: string;   // Chinese name
}

export interface EmojiCategory {
  id: string;
  title: string;
  items: EmojiEntry[];
}

export interface EmojiSection {
  id: string;
  title: string;
  categories: EmojiCategory[];
}

export const emojiSections: EmojiSection[] = ${JSON.stringify(sections, null, 2)};
`;

fs.writeFileSync(outPath, output, 'utf-8');
console.log(`Written to: ${path.relative(rootDir, outPath)}`);

function slugify(text) {
  return text
    .replace(/[^一-龥a-zA-Z0-9]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
    .toLowerCase();
}
